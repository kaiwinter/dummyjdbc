package me.avogadro.mockjdbc.connection.impl;

import java.io.File;
import java.sql.CallableStatement;
import java.sql.PreparedStatement;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.Collections;
import java.util.Map;

import me.avogadro.mockjdbc.connection.ConnectionAdapter;
import me.avogadro.mockjdbc.statement.impl.CsvCallableStatement;
import me.avogadro.mockjdbc.statement.impl.CsvPreparedStatement;
import me.avogadro.mockjdbc.statement.impl.CsvStatement;

/**
 * Connection which implements the methods {@link #createStatement()} and {@link #prepareStatement(String)}. The
 * {@link MockConnection} tries to open a CSV file in the directory <code>./table/</code> with the name
 * <code>&lt;tablename&gt;.csv</code> and returns the contained values. The query result will contain all values from
 * the file, it will not be narrowed by the query. The first line of the CSV file has to contain the column names.
 *
 * @author Kai Winter
 */
public class MockConnection extends ConnectionAdapter {

	private Map<String, File> tableResources;

	private final String url;

	/**
	 * Constructs a new {@link MockConnection}.
	 * @param tableResources {@link Map} of table name to CSV file.
	 */
	public MockConnection(Map<String, File> tableResources) {
		this(tableResources, "");
	}

	/**
	 * Constructs a new {@link MockConnection}.
	 * @param tableResources {@link Map} of table name to CSV file.
	 * @param url the JDBC URL used to open the connection
	 */
	public MockConnection(Map<String, File> tableResources, String url) {
		this.url = url == null ? "" : url;
		if (tableResources == null) {
			this.tableResources = Collections.emptyMap();
		} else {
			this.tableResources = tableResources;
		}
	}

	@Override
	protected String getConnectionUrl() {
		return url;
	}

	@Override
	protected Map<String, File> getTableResources() {
		return tableResources;
	}

	@Override
	public Statement createStatement() throws SQLException {
		return new CsvStatement(tableResources);
	}

	@Override
	public Statement createStatement(int resultSetType, int resultSetConcurrency) throws SQLException {
		return createStatement();
	}

	@Override
	public Statement createStatement(int resultSetType, int resultSetConcurrency, int resultSetHoldability) throws SQLException {
		return createStatement();
	}

	@Override
	public PreparedStatement prepareStatement(String sql) throws SQLException {
		return new CsvPreparedStatement(tableResources, sql);
	};

	@Override
	public CallableStatement prepareCall(String sql) throws SQLException {
		return new CsvCallableStatement(tableResources, sql);
	}

	@Override
	public CallableStatement prepareCall(String sql, int resultSetType, int resultSetConcurrency) throws SQLException {
		return prepareCall(sql);
	}

	@Override
	public CallableStatement prepareCall(String sql, int resultSetType, int resultSetConcurrency,
			int resultSetHoldability) throws SQLException {
		return prepareCall(sql);
	}

	@Override
	public PreparedStatement prepareStatement(String sql, int[] columnIndexes) throws SQLException {
		return prepareStatement(sql);
	}

	@Override
	public PreparedStatement prepareStatement(String sql, String[] columnNames) throws SQLException {
		return prepareStatement(sql);
	}

	@Override
	public PreparedStatement prepareStatement(String sql, int autoGeneratedKeys) throws SQLException {
		return prepareStatement(sql);
	}

	@Override
	public PreparedStatement prepareStatement(String sql, int resultSetType, int resultSetConcurrency) throws SQLException {
		return prepareStatement(sql);
	}

	@Override
	public PreparedStatement prepareStatement(String sql, int resultSetType, int resultSetConcurrency, int resultSetHoldability) throws SQLException {
		return prepareStatement(sql);
	}
}
